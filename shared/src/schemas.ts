import { z } from 'zod';
import { DIFFICULTIES } from './games/sudoku/types';
import { EMOTES } from './emotes';
import { PLAYER_COLORS } from './players';

// In a browser the page has a Content-Security-Policy without 'unsafe-eval', and zod would report a violation
// when it checks whether it may compile validators (the check calls Function). That compiled path is only a
// speed-up: the browser validates a room id, while the server keeps it for the payloads of every connection.
// (This is a side effect of loading the module: do not mark this package as free of side effects.)
if (typeof window !== 'undefined') z.config({ jitless: true });

/**
 * Runtime schemas for every payload a client can send to the server.
 *
 * TypeScript types are erased at runtime, so the server cannot trust them:
 * anything coming from a socket is `unknown` until it has been parsed here.
 * The TypeScript payload types are derived from these schemas, so the
 * validation and the contract can never drift apart.
 */

export const difficultySchema = z.enum(DIFFICULTIES);

export const emoteSchema = z.enum(EMOTES);

export const playerColorSchema = z.enum(PLAYER_COLORS);

/** The length of the UUID the app generates for a room (crypto.randomUUID()). */
export const MAX_ROOM_ID_LENGTH = 36;

/**
 * Room ids appear in URLs (/play/[roomId]) and are the only thing that keeps a game private. The server only
 * accepts the ones the app generates: a name that people can choose is a name that two groups can choose.
 */
export const roomIdSchema = z.uuidv4().transform((id) => id.toLowerCase());

export const MAX_PLAYER_ID_LENGTH = 64;

/**
 * Identity of a player across reconnections: generated by the browser and sent in
 * the handshake (`auth.playerId`). It is not a secret, only a stable label, so the
 * server accepts any short URL-safe string and falls back to the socket id otherwise.
 */
export const playerIdSchema = z
  .string()
  .min(8)
  .max(MAX_PLAYER_ID_LENGTH)
  .regex(/^[A-Za-z0-9_-]+$/);

const coordinateSchema = z.number().int().nonnegative();

/** Upper bounds depend on the board size, so they are checked by the server. */
export const cellUpdatePayloadSchema = z.object({
  r: coordinateSchema,
  c: coordinateSchema,
  v: z.number().int().nonnegative(),
});

export const toggleNotePayloadSchema = z.object({
  r: coordinateSchema,
  c: coordinateSchema,
  v: z.number().int().positive(),
});

/** `null` means "deselect"; row and column must be both set or both null. */
export const selectCellPayloadSchema = z
  .object({
    r: coordinateSchema.nullable(),
    c: coordinateSchema.nullable(),
  })
  .refine(({ r, c }) => (r === null) === (c === null));

export type CellUpdatePayload = z.infer<typeof cellUpdatePayloadSchema>;
/** `ok: false` means the server did not apply the move, so the client must resynchronize. */
export interface CellUpdateResult {
  ok: boolean;
}
export type ToggleNotePayload = z.infer<typeof toggleNotePayloadSchema>;
export type SelectCellPayload = z.infer<typeof selectCellPayloadSchema>;

/**
 * Argument lists of the client-to-server events, as tuples.
 * Socket.IO passes the arguments positionally, so each event is validated
 * as a whole argument list (extra or missing arguments are rejected).
 */
export const joinRoomArgsSchema = z.tuple([roomIdSchema, difficultySchema]);
/** Socket.IO appends the acknowledgement callback to the arguments when the client asks for one. */
const acknowledgementSchema = z.custom<(result: CellUpdateResult) => void>((value) => typeof value === 'function');

export const cellUpdateArgsSchema = z.tuple([cellUpdatePayloadSchema, acknowledgementSchema.optional()]);
export const toggleNoteArgsSchema = z.tuple([toggleNotePayloadSchema]);
export const selectCellArgsSchema = z.tuple([selectCellPayloadSchema]);
export const restartGameArgsSchema = z.tuple([difficultySchema]);
export const sendEmoteArgsSchema = z.tuple([emoteSchema]);
export const setColorArgsSchema = z.tuple([playerColorSchema]);
