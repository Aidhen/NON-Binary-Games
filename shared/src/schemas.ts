import { z } from 'zod';
import { DIFFICULTIES } from './games/sudoku/types';
import { WORD_LANGUAGES } from './games/word-search/types';
import { EMOTES } from './emotes';
import { GAME_IDS } from './games';
import { FEEDBACK_DEVICES, FEEDBACK_FREQUENCIES, FEEDBACK_RATINGS, FEEDBACK_WHAT, FEEDBACK_WHERE, FEEDBACK_WISHES } from './feedback';
import { PLAYER_COLORS } from './players';

// In a browser the page has a Content-Security-Policy without 'unsafe-eval', and zod would report a violation
// when it checks whether it may compile validators (the check calls Function). That compiled path is only a
// speed-up: the browser validates a room id, while the server keeps it for the payloads of every connection.
// (This is a side effect of loading the module: do not mark this package as free of side effects.)
if (typeof window !== 'undefined') z.config({ jitless: true });

/**
 * Runtime schemas for every payload a client can send to the server.
 *
 * TypeScript types are erased at runtime, so the server cannot trust them:
 * anything coming from a socket is `unknown` until it has been parsed here.
 * The TypeScript payload types are derived from these schemas, so the
 * validation and the contract can never drift apart.
 */

export const difficultySchema = z.enum(DIFFICULTIES);

export const emoteSchema = z.enum(EMOTES);

export const playerColorSchema = z.enum(PLAYER_COLORS);

export const gameIdSchema = z.enum(GAME_IDS);

/** The language of the words of a Word Search. It is a choice of the room, not of the interface of each player. */
export const wordLanguageSchema = z.enum(WORD_LANGUAGES);

/** The length of the UUID the app generates for a room (crypto.randomUUID()). */
export const MAX_ROOM_ID_LENGTH = 36;

/**
 * Room ids appear in URLs (/play/[roomId]) and are the only thing that keeps a game private. The server only
 * accepts the ones the app generates: a name that people can choose is a name that two groups can choose.
 */
export const roomIdSchema = z.uuidv4().transform((id) => id.toLowerCase());

export const MAX_PLAYER_ID_LENGTH = 64;

/**
 * Identity of a player across reconnections: generated by the browser and sent in
 * the handshake (`auth.playerId`). It is not a secret, only a stable label, so the
 * server accepts any short URL-safe string and falls back to the socket id otherwise.
 */
export const playerIdSchema = z
  .string()
  .min(8)
  .max(MAX_PLAYER_ID_LENGTH)
  .regex(/^[A-Za-z0-9_-]+$/);

const coordinateSchema = z.number().int().nonnegative();

/** Upper bounds depend on the board size, so they are checked by the server. */
export const cellUpdatePayloadSchema = z.object({
  r: coordinateSchema,
  c: coordinateSchema,
  v: z.number().int().nonnegative(),
});

export const toggleNotePayloadSchema = z.object({
  r: coordinateSchema,
  c: coordinateSchema,
  v: z.number().int().positive(),
});

/** `null` means "deselect"; row and column must be both set or both null. */
export const selectCellPayloadSchema = z
  .object({
    r: coordinateSchema.nullable(),
    c: coordinateSchema.nullable(),
  })
  .refine(({ r, c }) => (r === null) === (c === null));

/** A cell of the Flower Field. Upper bounds depend on the size of the field, so they are checked by the server. */
export const flowerFieldCellPayloadSchema = z.object({
  r: coordinateSchema,
  c: coordinateSchema,
});

/** `explosive`: opening a mine loses the game for the whole room, instead of only marking the cell. */
export const flowerFieldModePayloadSchema = z.object({
  explosive: z.boolean(),
});

/** The two ends of what a player selected in the Word Search. The server decides whether it is a word: bounds depend on the size of the grid. */
export const wordSearchSelectPayloadSchema = z.object({
  from: z.object({ r: coordinateSchema, c: coordinateSchema }),
  to: z.object({ r: coordinateSchema, c: coordinateSchema }),
});

/** A card of the Memory, by its place in the deck. The upper bound depends on the deck, so it is checked by the server. */
export const memoryFlipPayloadSchema = z.object({
  index: coordinateSchema,
});

export const wordSearchLanguagePayloadSchema = z.object({
  language: wordLanguageSchema,
});

export type CellUpdatePayload = z.infer<typeof cellUpdatePayloadSchema>;
/** `ok: false` means the server did not apply the move, so the client must resynchronize. */
export interface CellUpdateResult {
  ok: boolean;
}
/** The filled cells of the Sudoku whose number is not the one of the solution, as [row, column]. */
export interface SudokuMistakesResult {
  cells: [number, number][];
}
export type ToggleNotePayload = z.infer<typeof toggleNotePayloadSchema>;
export type SelectCellPayload = z.infer<typeof selectCellPayloadSchema>;
export type FlowerFieldCellPayload = z.infer<typeof flowerFieldCellPayloadSchema>;
export type FlowerFieldModePayload = z.infer<typeof flowerFieldModePayloadSchema>;
export type WordSearchSelectPayload = z.infer<typeof wordSearchSelectPayloadSchema>;
export type WordSearchLanguagePayload = z.infer<typeof wordSearchLanguagePayloadSchema>;
export type MemoryFlipPayload = z.infer<typeof memoryFlipPayloadSchema>;

/**
 * Argument lists of the client-to-server events, as tuples.
 * Socket.IO passes the arguments positionally, so each event is validated
 * as a whole argument list (extra or missing arguments are rejected).
 */
export const joinRoomArgsSchema = z.tuple([roomIdSchema]);
/** `null` takes the vote back. */
export const voteGameArgsSchema = z.tuple([gameIdSchema.nullable()]);
/** `false` takes the vote back. */
export const voteTableArgsSchema = z.tuple([z.boolean()]);
/** Socket.IO appends the acknowledgement callback to the arguments when the client asks for one. */
const acknowledgementSchema = z.custom<(result: CellUpdateResult) => void>((value) => typeof value === 'function');

export const cellUpdateArgsSchema = z.tuple([cellUpdatePayloadSchema, acknowledgementSchema.optional()]);
/** No payload: only the callback for the answer, which is what the question is for. */
export const sudokuMistakesArgsSchema = z.tuple([z.custom<(result: SudokuMistakesResult) => void>((value) => typeof value === 'function')]);
export const toggleNoteArgsSchema = z.tuple([toggleNotePayloadSchema]);
export const selectCellArgsSchema = z.tuple([selectCellPayloadSchema]);
export const flowerFieldCellArgsSchema = z.tuple([flowerFieldCellPayloadSchema]);
export const flowerFieldModeArgsSchema = z.tuple([flowerFieldModePayloadSchema]);
export const wordSearchSelectArgsSchema = z.tuple([wordSearchSelectPayloadSchema]);
export const wordSearchLanguageArgsSchema = z.tuple([wordSearchLanguagePayloadSchema]);
export const memoryFlipArgsSchema = z.tuple([memoryFlipPayloadSchema]);
export const restartGameArgsSchema = z.tuple([difficultySchema]);
export const sendEmoteArgsSchema = z.tuple([emoteSchema]);
export const setColorArgsSchema = z.tuple([playerColorSchema]);

/**
 * The body of `POST /feedback` (HTTP, not a socket event, but the same rule: it is `unknown` until it is parsed here).
 * Closed values only, and strict objects: a field that is not in the list is a refusal, not something to ignore.
 */
const feedbackWhereSchema = z.enum(FEEDBACK_WHERE);

export const feedbackArgsSchema = z.discriminatedUnion('kind', [
  z.strictObject({
    kind: z.literal('bug'),
    where: feedbackWhereSchema,
    what: z.enum(FEEDBACK_WHAT),
    device: z.enum(FEEDBACK_DEVICES),
    frequency: z.enum(FEEDBACK_FREQUENCIES),
  }),
  z.strictObject({
    kind: z.literal('opinion'),
    where: feedbackWhereSchema,
    rating: z.number().int().min(FEEDBACK_RATINGS[0]).max(FEEDBACK_RATINGS.at(-1)!),
    wishes: z.array(z.enum(FEEDBACK_WISHES)).max(FEEDBACK_WISHES.length).refine((wishes) => new Set(wishes).size === wishes.length).optional(),
    emote: emoteSchema.optional(),
  }),
]);

export type FeedbackArgs = z.infer<typeof feedbackArgsSchema>;
